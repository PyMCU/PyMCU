"""Compile the C runtimes of the backend for RV32EC and write them into it as data.

  src/softfloat/softfloat.c -> src/csharp/lib/RISCVSoftFloat.g.cs  (SoftFloatRoutines)
  src/gc/gc.c               -> src/csharp/lib/RISCVGc.g.cs         (GcRoutines)

The backend emits the routines a program calls (and what they call) into the assembly it
hands to the assembler, so a program that uses neither floats nor the heap pays nothing and the
machine that builds firmware needs no C compiler. Rerun this after editing either source:

    python3 tools/gen_c_runtimes.py

The results are committed.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNTIMES = [
    (ROOT / "src" / "softfloat" / "softfloat.c", ROOT / "src" / "csharp" / "lib" / "RISCVSoftFloat.g.cs", "SoftFloatRoutines"),
    (ROOT / "src" / "gc" / "gc.c", ROOT / "src" / "csharp" / "lib" / "RISCVGc.g.cs", "GcRoutines"),
]

# s1 is the error register of the backend: the compiled routines must never touch it.
def gcc(src: Path) -> list[str]:
    return ["riscv32-unknown-elf-gcc", "-march=rv32ec_zicsr", "-mabi=ilp32e", "-Os", "-ffixed-s1",
            "-ffunction-sections", "-fno-pic", "-fno-asynchronous-unwind-tables",
            "-fno-unwind-tables", "-ffreestanding", "-nostdlib", "-fno-stack-protector", "-S",
            "-o", "-", str(src)]


def generate(src: Path, out_path: Path, member: str) -> None:
    asm = subprocess.run(gcc(src), check=True, capture_output=True, text=True).stdout

    # The compiler's markers for inline asm name the source file by absolute path, which would
    # make the generated file differ from one checkout to the next.
    asm = "\n".join(l for l in asm.splitlines() if not re.match(r'\s*# \d+ ".*"( \d+)*\s*$', l))

    blocks: dict[str, list[str]] = {}
    current = None
    for line in asm.splitlines():
        m = re.match(r'\s*\.section\s+\.text\.([A-Za-z0-9_]+),', line)
        if m:
            current = m.group(1)
            blocks[current] = []
            continue
        if current is None:
            continue                                    # the file header: .file, .attribute ...
        if re.match(r'\s*\.(ident|section\s+\.note)', line):
            current = None
            continue
        blocks[current].append(line)

    if "s1" in re.findall(r'\bs1\b', "\n".join("\n".join(b) for b in blocks.values())):
        sys.exit("the compiled routines use s1, the backend's error register")

    deps = {}
    for name, body in blocks.items():
        refs = set()
        for line in body:
            m = re.match(r'\s*(?:call|tail|jump|j|jal)\s+([A-Za-z_][A-Za-z0-9_]*)', line)
            if m and m.group(1) != name:
                refs.add(m.group(1))
        deps[name] = sorted(refs)

    out = []
    out.append(f"// <auto-generated> by tools/gen_c_runtimes.py from {src.relative_to(ROOT)}. Do not edit. </auto-generated>")
    out.append("// SPDX-License-Identifier: MIT")
    out.append("// Copyright (C) 2026 Ivan Montiel Cardona and the PyMCU Project Authors")
    out.append("")
    out.append("namespace PyMCU.Backend.Targets.RiscV;")
    out.append("")
    out.append("public partial class RiscvCodeGen")
    out.append("{")
    out.append("    // routine -> (assembly lines, routines it calls, among them the runtime's own __mulsi3)")
    out.append(f"    private static readonly Dictionary<string, (string[] Asm, string[] Calls)> {member} = new()")
    out.append("    {")
    for name in blocks:
        body = [l for l in blocks[name] if l.strip()]
        out.append(f'        ["{name}"] = (')
        out.append("            [")
        for l in body:
            out.append('                "' + l.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '",')
        out.append("            ],")
        out.append("            [" + ", ".join(f'"{d}"' for d in deps[name]) + "]),")
    out.append("    };")
    out.append("}")
    out_path.write_text("\n".join(out) + "\n")
    print(f"{out_path.relative_to(ROOT)}: {len(blocks)} routines")


def main() -> int:
    for src, out_path, member in RUNTIMES:
        generate(src, out_path, member)
    return 0


if __name__ == "__main__":
    sys.exit(main())
